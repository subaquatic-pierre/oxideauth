// --- ClientCreateRes ---
#[derive(Serialize)]
pub struct ClientCreateRes {
    pub id: Uuid,
    pub secret: String,
    pub workspace_id: Uuid,
    pub name: String,
    pub endpoint: Option<String>,
    pub description: Option<String>,
    pub tags: Vec<String>,
    pub meta: ClientMeta,
    #[serde(with = "time::serde::rfc3339")]
    pub created_at: OffsetDateTime,
    #[serde(with = "time::serde::rfc3339::option")]
    pub updated_at: Option<OffsetDateTime>,
}

impl From<Client> for ClientCreateRes {
    /// Converts to response DTO. The `secret` field is set to an empty string as a
    /// placeholder, because the service layer does not currently expose the plaintext
    /// secret on the returned `Client` model.
    fn from(client: Client) -> Self {
        Self {
            id: client.id,
            secret: String::new(),
            workspace_id: client.workspace_id,
            name: client.name,
            endpoint: client.endpoint,
            description: client.description,
            tags: client.tags,
            meta: client.meta,
            created_at: client.audit.created_at,
            updated_at: client.audit.updated_at,
        }
    }
}

impl From<(Client, String)> for ClientCreateRes {
    /// Converts to response DTO. The `String` is the raw client secret,
    /// which is generated by the service layer and only ever shown once.
    fn from((client, secret): (Client, String)) -> Self {
        Self {
            id: client.id,
            secret,
            workspace_id: client.workspace_id,
            name: client.name,
            endpoint: client.endpoint,
            description: client.description,
            tags: client.tags,
            meta: client.meta,
            created_at: client.audit.created_at,
            updated_at: client.audit.updated_at,
        }
    }
}

