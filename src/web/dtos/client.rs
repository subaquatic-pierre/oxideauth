// --- ClientDescribeReq ---
#[derive(Deserialize)]
pub struct ClientDescribeReq {
    pub id: Uuid,
    #[serde(default)]
    pub workspace_id: Option<Uuid>,
}

impl IntoParams<ClientDescribeParams> for ClientDescribeReq {
    fn into_params(self) -> CoreResult<ClientDescribeParams> {
        Ok(ClientDescribeParams {
            id: self.id,
            workspace_id: self.workspace_id,
        })
    }
}

// --- ClientDescribeRes ---
#[derive(Serialize, Debug)]
pub struct ClientDescribeRes {
    pub id: Uuid,
    pub name: String,
    pub endpoint: Option<String>,
    pub description: Option<String>,
    pub tags: Vec<String>,
    pub meta: ClientMeta,
    #[serde(with = "time::serde::rfc3339")]
    pub created_at: OffsetDateTime,
    #[serde(with = "time::serde::rfc3339::option")]
    pub updated_at: Option<OffsetDateTime>,
}

impl From<Client> for ClientDescribeRes {
    fn from(client: Client) -> Self {
        Self {
            id: client.id,
            name: client.name,
            endpoint: client.endpoint,
            description: client.description,
            tags: client.tags,
            meta: client.meta,
            created_at: client.audit.created_at,
            updated_at: client.audit.updated_at,
        }
    }
}

